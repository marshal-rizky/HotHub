// The outline of an icon as an SVG path on its 9 by 9 grid, for drawing it inside a larger picture.
export function iconPath(name) {
  let d = '';
  GRID[name].forEach((row, y) => {
    for (const run of row.matchAll(/#+/g)) d += `M${run.index} ${y}h${run[0].length}v1h-${run[0].length}z`;
  });
  return d;
}

export function icon(name) {
  const d = iconPath(name);
  return `<svg class="px" viewBox="0 0 9 9" shape-rendering="crispEdges" aria-hidden="true"><path fill="currentColor" d="${d}"/></svg>`;
}

// Fills every element that carries data-icon="name" inside root.
export function fillIcons(root) {
  for (const el of root.querySelectorAll('[data-icon]')) el.innerHTML = icon(el.dataset.icon);
}
